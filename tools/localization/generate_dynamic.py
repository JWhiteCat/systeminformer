#!/usr/bin/env python3
"""Generate the explicit UI-string catalog. English is the lookup/fallback key."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'phlib/include/uilang_zh_cn.h'


def catalog():
    result = {}
    for name in ('dynamic.zh-CN.json', 'plugins.zh-CN.json'):
        path = ROOT / 'localization' / name
        if not path.exists():
            continue
        values = json.loads(path.read_text(encoding='utf-8'))
        for source, target in values.items():
            if not isinstance(source, str) or not isinstance(target, str) or not target:
                raise ValueError(f'{path}: invalid translation {source!r}')
            if source in result and result[source] != target:
                raise ValueError(f'Conflicting translation for {source!r}')
            # Menu keyboard hints use backspace (custom EMenu) or tab (Win32).
            for separator in ('\b', '\t'):
                if source.partition(separator)[1:] != target.partition(separator)[1:]:
                    raise ValueError(f'Changed keyboard hint for {source!r}')
            if re.findall(r'(?<!&)&([^&])', source) != re.findall(r'(?<!&)&([^&])', target):
                raise ValueError(f'Changed mnemonic for {source!r}')
            if re.findall(r'%(?:[-+ #0]*\d*(?:\.\d+)?(?:I64|I32|ll|l|h|z|w)?[a-zA-Z]|%)', source) != re.findall(r'%(?:[-+ #0]*\d*(?:\.\d+)?(?:I64|I32|ll|l|h|z|w)?[a-zA-Z]|%)', target):
                raise ValueError(f'Changed format placeholders for {source!r}')
            result[source] = target
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    values = catalog()
    text = '// Generated by tools/localization/generate_dynamic.py; do not edit.\n'
    text += '// Sources: localization/dynamic.zh-CN.json and plugins.zh-CN.json.\n'
    for source, target in sorted(values.items()):
        text += '    { L' + json.dumps(source, ensure_ascii=True) + ', L' + json.dumps(target, ensure_ascii=True) + ' },\n'
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != text:
            sys.exit('UI catalog is stale; run tools/localization/generate_dynamic.py')
    else:
        OUTPUT.write_text(text, encoding='utf-8')
    print(f'UI catalog: {len(values)} translations; '+('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
