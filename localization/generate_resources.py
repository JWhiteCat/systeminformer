#!/usr/bin/env python3
"""Generate only localized UI resources; the English source remains authoritative."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = Path(__file__).with_name('resources.zh-CN.json')
SOURCES = [ROOT / 'SystemInformer/SystemInformer.rc'] + sorted(
    p for p in (ROOT / 'plugins').glob('*/*.rc') if p.name != 'version.rc' and not p.name.endswith('.zh-CN.rc')
)
START = re.compile(r'^(?:\w+\s+(?:DIALOGEX|DIALOG|MENU|MENUEX)\b|STRINGTABLE\b)')
CAPTION = re.compile(r'^(\s*(?:CAPTION|LTEXT|RTEXT|CTEXT|PUSHBUTTON|DEFPUSHBUTTON|GROUPBOX|CONTROL|MENUITEM|POPUP)\s+)"((?:""|[^"\n])*)"')
STRING_ENTRY = re.compile(r'^(\s*\w+\s+)"((?:""|[^"\n])*)"')


def blocks(source):
    lines = source.splitlines()
    result = []
    i = 0
    while i < len(lines):
        if not START.match(lines[i]):
            i += 1
            continue
        block = [lines[i]]
        depth = 0
        entered = False
        i += 1
        while i < len(lines):
            line = lines[i]
            block.append(line)
            i += 1
            if line.strip() == 'BEGIN':
                depth += 1
                entered = True
            elif line.strip() == 'END':
                depth -= 1
                if entered and depth == 0:
                    break
        if not entered or depth != 0:
            raise ValueError('Unbalanced resource: ' + block[0])
        result.append(block)
    return result


def render(source, catalog):
    output = ['// Generated by localization/generate_resources.py; do not edit.',
              '// English source resources are preserved as the fallback.',
              'LANGUAGE LANG_CHINESE, SUBLANG_CHINESE_SIMPLIFIED', '']
    used = set()
    for block in blocks(source):
        stringtable = block[0].startswith('STRINGTABLE')
        for line in block:
            match = (STRING_ENTRY if stringtable else CAPTION).match(line)
            if match:
                key = match[2].replace('""', '"')
                if key:
                    used.add(key)
                if key in catalog:
                    translated = catalog[key].replace('"', '""')
                    line = line[:match.start(2)] + translated + line[match.end(2):]
            output.append(line)
        output.append('')
    # Resource scripts sometimes append version resources after their UI include.
    # Encoding is selected by the build, not an included resource. MSBuild's
    # UTF-8-only /8 mode rejects code_page pragmas (RC4215).
    output += ['LANGUAGE LANG_ENGLISH, SUBLANG_ENGLISH_US', '']
    return '\n'.join(output), used


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated resources are stale')
    parser.add_argument('--missing', action='store_true', help='print untranslated captions')
    args = parser.parse_args()
    catalog = json.loads(CATALOG.read_text(encoding='utf-8'))
    missing = set()
    failures = []
    total = 0
    for path in SOURCES:
        source = path.read_text(encoding='utf-8-sig')
        target = path.with_name(path.stem + '.zh-CN.rc')
        text, used = render(source, catalog)
        missing.update(used - catalog.keys())
        total += len(blocks(source))
        if args.check:
            if not target.exists() or target.read_text(encoding='utf-8') != text:
                failures.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(text, encoding='utf-8')
    if args.missing:
        print('\n'.join(sorted(missing)))
    print(f'{total} UI resources; {len(catalog)} catalog entries; {len(missing)} untranslated/technical captions')
    if failures:
        raise SystemExit('Stale resources: ' + ', '.join(failures))


if __name__ == '__main__':
    main()
